package com.mairor.backend.common.security;

/**
 * 로그인 세션이 끝나기 직전에 호출되는 연동 지점. 세션에 묶인 데이터를 정리해야 하는 쪽(예: 가이드 중도 종료가 진행 중인 실행을 {@code ABANDONED} 로 바꾸는
 * 일)이 이 인터페이스를 구현해 빈으로 등록하면, 세션이 끝나는 모든 경로에서 호출된다. 구현이 하나도 없으면 아무 일도 일어나지 않는다.
 *
 * <p>호출되는 경로와 {@link SessionEndReason}:
 *
 * <ul>
 *   <li>로그아웃·기기 로그아웃·전체 로그아웃: 세션을 지우기 <b>전</b>. 구현이 예외를 던지면 세션을 지우지 않고 요청이 오류로 끝난다. 회원은 같은 요청을 다시
 *       보낼 수 있다.
 *   <li>절대 만료: 세션을 지우기 전. 예외를 던지면 세션을 남기고 401 로 응답한다. 다음 요청이나 유휴 만료 정리에서 다시 호출된다. 단 로그인처럼 인증 없이 열려
 *       있는 경로로 온 요청은 만료된 세션을 이어 쓰면 안 되므로 예외를 던져도 세션을 지우고 요청을 계속한다(이 경우 정리가 다시 시도되지 않는다).
 *   <li>유휴 만료: Redis 가 세션 키를 만료시킨 뒤({@link RedisSessionExpirationListener}). 예외를 던져도 다시 호출되지 않는다.
 *       실패는 로그와 지표로만 남는다.
 *   <li>로그인이 이전 세션을 대체: 지우기 전. 예외를 던져도 로그인은 막지 않는다. 실패는 로그와 지표로만 남는다.
 * </ul>
 *
 * <p>구현이 지켜야 할 것:
 *
 * <ul>
 *   <li><b>멱등이어야 한다.</b> 같은 세션에 두 번 이상 호출될 수 있다(실패 후 재시도, 서버 여러 대의 동시 처리).
 *   <li>요청 스레드에서 동기로 호출된다. 오래 걸리는 일은 비동기로 넘기고 빠른 상태 변경만 한다. 세션 삭제 트랜잭션 밖에서 호출되므로 필요하면 자기 트랜잭션을 연다.
 *   <li>세션이 이미 쓸 수 없는 상태(만료)일 수 있다. {@link SessionEnd#userId()}·{@link SessionEnd#sessionId()} 만
 *       믿고, 세션 속성은 읽지 않는다.
 *   <li>세션 ID 를 로그·응답·지표에 내보내지 않는다.
 *   <li>여러 구현이 있으면 {@code @Order} 순으로 호출되고, 엄격한 경로에서는 앞 구현이 실패하면 뒤 구현은 호출되지 않는다.
 * </ul>
 */
@FunctionalInterface
public interface SessionEndHook {

  /** 세션이 끝나기 직전에 호출된다. 던진 예외를 어떻게 다루는지는 경로마다 다르다(위 설명). */
  void beforeSessionEnds(SessionEnd end);
}
